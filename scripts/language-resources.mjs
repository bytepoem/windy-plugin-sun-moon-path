import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { readTranslationSources } from './translation-sources.mjs';

const sha = value => createHash('sha256').update(value).digest('hex');
const slots = value => (value.match(/\{\{\d+\}\}|\{provider\}/g) ?? []).sort().join('|');

/** One canonical byte representation per language; the manifest pins every byte.
 * Output is separate from dist so language payloads never enter the Windy archive. */
export async function languageResources(output, environment = 'release') {
    if (environment !== 'local' && environment !== 'release') throw new Error('Invalid language environment');
    const sources = JSON.parse(await readFile('src/locales/source.en.json', 'utf8'));
    if (JSON.stringify(sources) !== JSON.stringify(await readTranslationSources())) {
        throw new Error('English source contract is stale');
    }
    const contract = sha(JSON.stringify(Object.values(sources).sort()));
    const files = {};
    for (const filename of (await readdir('src/locales/generated')).filter(name => name.endsWith('.json')).sort()) {
        const language = filename.slice(0, -5);
        const catalog = JSON.parse(await readFile('src/locales/generated/' + filename, 'utf8'));
        if (Object.keys(catalog).sort().join() !== Object.keys(sources).sort().join()) throw new Error('Incomplete ' + language);
        const messages = Object.fromEntries(Object.entries(sources).map(([id, source]) => {
            const target = catalog[id];
            if (typeof target !== 'string' || !target.trim() || slots(source) !== slots(target)) throw new Error('Invalid ' + language + '/' + id);
            return [source, target];
        }));
        files[language] = JSON.stringify({ schema: 1, language, contract, messages }) + '\n';
    }
    if (Object.keys(files).length !== 40) throw new Error('Expected 40 languages');
    const hashes = Object.fromEntries(Object.entries(files).map(([code, text]) => [code, sha(text)]));
    const manifest = { version: sha(JSON.stringify(hashes)), contract, count: Object.keys(sources).length, hashes };
    if (output) {
        const directory = resolve(output, 'languages', environment, manifest.version);
        await mkdir(directory, { recursive: true });
        for (const [code, text] of Object.entries(files)) await writeFile(resolve(directory, code + '.json'), text);
        await writeFile(resolve(output, 'manifest.json'), JSON.stringify({ environment, ...manifest }) + '\n');
    }
    return manifest;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
    const manifest = await languageResources(process.argv[2]?.startsWith('--') ? undefined : process.argv[2]);
    const content = '/** Generated by scripts/language-resources.mjs; pins immutable JSON resources. */\nexport const languageManifest = ' + JSON.stringify(manifest, null, 4) + ';\n';
    const path = 'src/languageManifest.ts';
    if (process.argv.includes('--check')) {
        if (await readFile(path, 'utf8') !== content) throw new Error('Language manifest is stale');
    } else if (!process.argv[2]) {
        let old = '';
        try { old = await readFile(path, 'utf8'); } catch { /* First generation. */ }
        console.log('*** Begin Patch\n*** ' + (old ? 'Update' : 'Add') + ' File: ' + path + '\n' + (old ? '@@\n' + old.trimEnd().split('\n').map(line => '-' + line).join('\n') + '\n' : '') + content.trimEnd().split('\n').map(line => '+' + line).join('\n') + '\n*** End Patch');
    }
}
